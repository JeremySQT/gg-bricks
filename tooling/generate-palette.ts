// Generate foundations/tokens/base/primitives/colors.tokens.json from foundations/palette.config.json.
// Ramps are computed in OKLCH (even lightness per step, hue-specific chroma reduced into the sRGB
// gamut) and written as DTCG sRGB colors with components in 0–1. Deterministic: same config, same file.
//   node tooling/generate-palette.ts
import { readJson, write } from './lib/paths.ts';
import { oklchToSrgb } from './lib/color.ts';
import type { Color, SourceToken } from './lib/types.ts';

interface HueSpec {
  hue: number;
  chroma: number;
}
interface PaletteConfig {
  steps: { neutral: Record<string, number>; hue: Record<string, number> };
  chromaShape: Record<string, number>;
  neutral: HueSpec;
  hues: Record<string, HueSpec>;
  alpha: { black: number[]; white: number[] };
}

export const paletteConfigPath = 'foundations/palette.config.json';
export const colorsPath = 'foundations/tokens/base/primitives/colors.tokens.json';

const round = (x: number): number => Math.round(x * 1e6) / 1e6;
const color = (components: [number, number, number], alpha = 1): SourceToken => ({
  $type: 'color',
  $value: { colorSpace: 'srgb', components: components.map(round) as Color['components'], alpha } satisfies Color
});
const ramp = (spec: HueSpec, steps: Record<string, number>, shape?: Record<string, number>) =>
  Object.fromEntries(
    Object.entries(steps).map(([step, L]) => [
      step,
      color(oklchToSrgb(L, spec.chroma * (shape ? (shape[step] ?? 1) : 1), spec.hue))
    ])
  );

export function generatePalette(cfg: PaletteConfig): Record<string, unknown> {
  const c: Record<string, unknown> = {
    transparent: color([0, 0, 0], 0),
    neutral: ramp(cfg.neutral, cfg.steps.neutral)
  };
  for (const [name, spec] of Object.entries(cfg.hues)) c[name] = ramp(spec, cfg.steps.hue, cfg.chromaShape);
  c.alpha = {
    black: Object.fromEntries(cfg.alpha.black.map((a) => [String(a), color([0, 0, 0], a / 100)])),
    white: Object.fromEntries(cfg.alpha.white.map((a) => [String(a), color([1, 1, 1], a / 100)]))
  };
  return {
    $description: `Generated by tooling/generate-palette.ts from ${paletteConfigPath}. Do not edit.`,
    primitive: { color: c }
  };
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split(/[\\/]/).pop() ?? '')) {
  const cfg = readJson<PaletteConfig>(paletteConfigPath);
  write(colorsPath, generatePalette(cfg));
  console.log(`Wrote ${colorsPath}: neutral + ${Object.keys(cfg.hues).length} hues + alpha`);
}

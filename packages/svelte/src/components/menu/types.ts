import type { Snippet } from 'svelte';
import type { HTMLAttributes } from 'svelte/elements';
import type { MenuAlign, MenuItemIntent, MenuSide } from './contract.generated.js';

/** Attributes the trigger snippet spreads on its Button or IconButton. */
export interface MenuTriggerProps {
  id: string;
  popovertarget: string;
  'aria-haspopup': 'menu';
  'aria-expanded': boolean;
  'aria-controls': string;
  onkeydown: (event: KeyboardEvent) => void;
  onpointerdown: (event: PointerEvent) => void;
}

type Owned = 'children' | 'role' | 'aria-label' | 'aria-labelledby' | 'popover' | 'id' | 'onselect';

export interface MenuProps extends Omit<HTMLAttributes<HTMLDivElement>, Owned> {
  /** Shown state; bind it (`bind:open`). */
  open?: boolean;
  /** Accessible name of the menu; by default the trigger names it. */
  label?: string;
  /** Preferred side; flips when the viewport lacks room. Default bottom. */
  side?: MenuSide;
  /** Alignment with the trigger, in the reading direction. Default start. */
  align?: MenuAlign;
  /** Renders the trigger, a Button or IconButton: spread `props` on it (`<IconButton label="More" {...props} />`). */
  trigger: Snippet<[MenuTriggerProps]>;
  /** MenuItem, MenuSeparator and MenuGroup children. */
  children: Snippet;
  /** Called with the value of the item the user activates. */
  onselect?: (value: string) => void;
  /** Called when the user opens or closes the menu. */
  onopenchange?: (open: boolean) => void;
  /** id of the menu panel (generated by default); the trigger gets `<id>-trigger`. */
  id?: string;
  /** The menu panel element. */
  ref?: HTMLDivElement | null;
}

type ItemOwned = 'children' | 'role' | 'tabindex' | 'aria-disabled';

export interface MenuItemProps extends Omit<HTMLAttributes<HTMLElement>, ItemOwned> {
  /** The action (Rename). Required and non-empty: the item's accessible name, on one line. */
  label: string;
  /** Identifies the item in `onselect`; defaults to the label. */
  value?: string;
  /** danger paints a destructive action (Delete) in the danger color. Default neutral. */
  intent?: MenuItemIntent;
  /** Navigates to this address as a link when activated (and still reports `onselect`). */
  href?: string;
  /** Stays in the menu, reached by the arrow keys and announced unavailable; activating it does nothing. */
  disabled?: boolean;
  /** One decorative icon before the label (16 px, in the item's color). */
  leading?: Snippet;
  /** One Shortcut showing the keyboard shortcut of the same action elsewhere (display only). */
  trailing?: Snippet;
}

export interface MenuGroupProps extends Omit<HTMLAttributes<HTMLDivElement>, 'children' | 'role'> {
  /** The heading shown above the items; it names the group. Required and non-empty. */
  label: string;
  /** MenuItem children. */
  children: Snippet;
}

export type MenuSeparatorProps = Omit<HTMLAttributes<HTMLDivElement>, 'children' | 'role'>;

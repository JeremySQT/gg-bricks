import type { Snippet } from 'svelte';
import type { HTMLAttributes, HTMLButtonAttributes } from 'svelte/elements';
import type { TabsActivation, TabsOrientation, TabsSize } from './contract.generated.js';

type Owned = 'children' | 'role' | 'id';

export interface TabsProps extends Omit<HTMLAttributes<HTMLDivElement>, Owned> {
  /** Value of the selected tab; bind it (`bind:value`). When it matches no enabled tab, the first enabled tab shows. */
  value?: string;
  /** Accessible name of the tab list (often the heading of the area the tabs switch). */
  label?: string;
  /** Size of the tabs (height, text, padding). Default md. */
  size?: TabsSize;
  /** horizontal: a row above the panels; vertical: a column at the inline start. Default horizontal. */
  orientation?: TabsOrientation;
  /** automatic selects the tab focus moves to; manual waits for Enter or Space (slow panels). Default automatic. */
  activation?: TabsActivation;
  /** The TabsTrigger children, in order. */
  list: Snippet;
  /** The TabsPanel children, one per tab value. */
  children: Snippet;
  /** Called with the value of the tab the user selects. */
  onvaluechange?: (value: string) => void;
  /** Base id (generated by default): tabs get `<id>-tab-<value>`, panels `<id>-panel-<value>`. */
  id?: string;
  /** The root element. */
  ref?: HTMLDivElement | null;
}

type TriggerOwned = 'children' | 'role' | 'id' | 'type' | 'tabindex' | 'aria-selected' | 'aria-controls' | 'value';

export interface TabsTriggerProps extends Omit<HTMLButtonAttributes, TriggerOwned> {
  /** The tab's text; required and non-empty, its accessible name, on one line. */
  label: string;
  /** Identifies the tab and its panel. Required. */
  value: string;
  /** Shown unavailable, never selected, skipped by the arrow keys. */
  disabled?: boolean;
  /** One decorative icon before the label, sized by the tab. */
  leading?: Snippet;
  /** One Counter or Badge after the label (give it the tab's size). */
  trailing?: Snippet;
}

export interface TabsPanelProps extends Omit<HTMLAttributes<HTMLDivElement>, 'role' | 'id' | 'hidden'> {
  /** The value of the tab that shows this panel. Required. */
  value: string;
  /** The panel content. */
  children: Snippet;
}

/** Shared by Tabs and its children (context key `ggb:tabs`). */
export interface TabsContext {
  readonly selected: string;
  readonly size: TabsSize;
  readonly orientation: TabsOrientation;
  register(value: string, disabled: () => boolean): () => void;
  select(value: string): void;
  tabId(value: string): string;
  panelId(value: string): string;
}

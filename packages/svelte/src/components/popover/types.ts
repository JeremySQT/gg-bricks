import type { Snippet } from 'svelte';
import type { HTMLAttributes } from 'svelte/elements';
import type { PopoverAlign, PopoverSide } from './contract.generated.js';

/** Attributes the trigger snippet spreads on its Button or IconButton. */
export interface PopoverTriggerProps {
  id: string;
  popovertarget: string;
  'aria-haspopup': 'dialog';
  'aria-expanded': boolean;
  'aria-controls': string;
}

type Owned = 'children' | 'role' | 'aria-label' | 'popover' | 'id';

export interface PopoverProps extends Omit<HTMLAttributes<HTMLDivElement>, Owned> {
  /** Shown state; bind it (`bind:open`). */
  open?: boolean;
  /** Accessible name of the panel (often its visible heading). Required and non-empty. */
  label: string;
  /** Preferred side; flips when the viewport lacks room. Default bottom. */
  side?: PopoverSide;
  /** Alignment with the trigger, in the reading direction. Default start. */
  align?: PopoverAlign;
  /** Renders the trigger, a Button or IconButton: spread `props` on it (`<Button label="Filters" {...props} />`). */
  trigger: Snippet<[PopoverTriggerProps]>;
  /** The content of the panel. */
  children: Snippet;
  /** Called when the user opens or closes the popover. */
  onopenchange?: (open: boolean) => void;
  /** id of the panel (generated by default); the trigger gets `<id>-trigger`. */
  id?: string;
  /** The panel element. */
  ref?: HTMLDivElement | null;
}

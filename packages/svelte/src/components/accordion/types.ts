import type { Snippet } from 'svelte';
import type { HTMLAttributes } from 'svelte/elements';

export interface AccordionProps extends Omit<HTMLAttributes<HTMLDivElement>, 'children'> {
  /** Values of the expanded items; bind it (`bind:value`). */
  value?: string[];
  /** Items expand independently; otherwise at most one is expanded (it can be collapsed). Default false. */
  multiple?: boolean;
  /** Level of the heading around each trigger (2 to 6), to fit the page outline. Default 3. */
  headingLevel?: number;
  /** AccordionItem children. */
  children: Snippet;
  /** Called with the values of the expanded items after the user expands or collapses one. */
  onvaluechange?: (value: string[]) => void;
  /** The root element. */
  ref?: HTMLDivElement | null;
}

export interface AccordionItemProps extends Omit<HTMLAttributes<HTMLDivElement>, 'children' | 'id'> {
  /** Identifies the item in the accordion's value. Required. */
  value: string;
  /** The heading text; required and non-empty, the trigger's accessible name; it wraps when long. */
  label: string;
  /** Cannot be toggled and keeps its state; skipped by the arrow keys. */
  disabled?: boolean;
  /** One decorative icon before the label. */
  leading?: Snippet;
  /** The section shown when the item is expanded. */
  children: Snippet;
  /** Base id (generated by default): the trigger gets `<id>-trigger`, the content `<id>-content`. */
  id?: string;
}

/** Shared by Accordion and its items (context key `ggb:accordion`). */
export interface AccordionContext {
  readonly headingLevel: number;
}

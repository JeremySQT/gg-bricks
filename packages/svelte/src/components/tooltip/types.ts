import type { Snippet } from 'svelte';
import type { TooltipAlign, TooltipSide } from './contract.generated.js';

export interface TooltipProps {
  /** The short text shown on hover and focus. Required and non-empty; plain text only. */
  label: string;
  /** Preferred side; it flips when the viewport lacks room. Default top. */
  side?: TooltipSide;
  /** Alignment with the trigger. Default center. */
  align?: TooltipAlign;
  /** Shown state; bind it to control the tooltip (`bind:open`). */
  open?: boolean;
  /** Exactly one focusable Button, IconButton or Link: the trigger. */
  children: Snippet;
  /** Called when the user opens or closes the tooltip (hover, focus, Escape, leaving, activation). */
  onopenchange?: (open: boolean) => void;
  /** id of the tooltip element (generated by default). */
  id?: string;
}
